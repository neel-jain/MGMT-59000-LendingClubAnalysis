"""
test_risk_scoring.py
======================
Unit tests for src/risk_scoring.py.

Uses the real Phase 3 serialized model artifacts (regenerated by the
synthetic-fixture pipeline) via `RiskScoringEngine`'s default disk-
loading path, plus a lightweight injected-pipeline path for tests that
need a controlled, fast model.

Run with:
    pytest tests/ -v
"""

import sys
import warnings
from pathlib import Path

import numpy as np
import pytest

warnings.filterwarnings("ignore")

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import model_utils, utils  # noqa: E402
from src.configurable_thresholds import RiskThresholdConfig  # noqa: E402
from src.risk_scoring import RiskScoringEngine, expand_threshold_analysis, plot_expanded_threshold_analysis  # noqa: E402


@pytest.fixture(scope="module")
def splits():
    return utils.load_splits()


@pytest.fixture(scope="module")
def quick_pipeline(splits):
    """A cheaply-trained Logistic Regression pipeline for fast, isolated tests (avoids a full Phase 3 hyperparameter search)."""
    X_train, X_val, X_test, y_train, y_val, y_test = splits
    pipeline = model_utils.build_logistic_regression_pipeline()
    pipeline.fit(X_train, y_train)
    return pipeline


@pytest.fixture
def engine(quick_pipeline):
    return RiskScoringEngine(model_key="logistic_regression", pipeline=quick_pipeline)


# ---------------------------------------------------------------------------
# Construction
# ---------------------------------------------------------------------------


def test_engine_construction_with_injected_pipeline(quick_pipeline):
    engine = RiskScoringEngine(model_key="logistic_regression", pipeline=quick_pipeline)
    assert engine.model_key == "logistic_regression"
    assert 0.0 <= engine._decision_threshold <= 1.0


def test_engine_construction_invalid_model_key_raises(quick_pipeline):
    with pytest.raises(ValueError):
        RiskScoringEngine(model_key="not_a_real_model", pipeline=quick_pipeline)


# ---------------------------------------------------------------------------
# Core prediction
# ---------------------------------------------------------------------------


def test_predict_probability_shape_and_range(engine, splits):
    _, _, X_test, _, _, _ = splits
    proba = engine.predict_probability(X_test)
    assert len(proba) == len(X_test)
    assert (proba >= 0).all() and (proba <= 1).all()


def test_predict_uses_recommended_threshold_by_default(engine, splits):
    _, _, X_test, _, _, _ = splits
    predictions = engine.predict(X_test)
    proba = engine.predict_probability(X_test)
    expected = (proba >= engine._decision_threshold).astype(int)
    assert np.array_equal(predictions, expected)


def test_predict_with_explicit_threshold_override(engine, splits):
    _, _, X_test, _, _, _ = splits
    predictions = engine.predict(X_test, threshold=0.99)
    # Almost nothing should be flagged at a 0.99 cutoff.
    assert predictions.sum() <= 1


