def test_custom_threshold_config_changes_tier_assignment(quick_pipeline):
    from src.configurable_thresholds import RiskTierBoundary, LendingActionRule, LoanGradeBand

    custom = RiskThresholdConfig(
        risk_tiers=[
            RiskTierBoundary("Low Risk", 0.0, 0.99, "everything is low risk"),
            RiskTierBoundary("Very High Risk", 0.99, 1.01, "almost nothing"),
        ],
        lending_actions=[
            LendingActionRule("Low Risk", "Approve", "d"),
            LendingActionRule("Very High Risk", "Decline", "d"),
        ],
        interest_rate_adjustment_bps={"Low Risk": 0.0, "Very High Risk": 500.0},
        loan_grade_bands=[LoanGradeBand("A", 0.0, 1.01)],
    )
    engine = RiskScoringEngine(model_key="logistic_regression", pipeline=quick_pipeline, threshold_config=custom)
    assert engine.assign_risk_tier(0.5) == "Low Risk"  # would be High/Moderate under defaults


