def test_expand_threshold_analysis_has_new_columns():
    rng = np.random.default_rng(0)
    y_true = rng.integers(0, 2, 200)
    y_proba = rng.uniform(0, 1, 200)
    table = expand_threshold_analysis(y_true, y_proba, thresholds=[0.2, 0.5, 0.8])
    assert {"approval_rate", "false_positive_rate", "false_negative_rate"} <= set(table.columns)
    assert (table["approval_rate"] >= 0).all() and (table["approval_rate"] <= 1).all()


def test_expand_threshold_analysis_approval_rate_decreases_with_threshold():
    rng = np.random.default_rng(0)
    y_true = rng.integers(0, 2, 300)
    y_proba = rng.uniform(0, 1, 300)
    table = expand_threshold_analysis(y_true, y_proba, thresholds=[0.1, 0.5, 0.9])
    approval_rates = table.sort_values("threshold")["approval_rate"].tolist()
    assert approval_rates[0] <= approval_rates[1] <= approval_rates[2]


def test_plot_expanded_threshold_analysis_runs():
    rng = np.random.default_rng(0)
    y_true = rng.integers(0, 2, 100)
    y_proba = rng.uniform(0, 1, 100)
    table = expand_threshold_analysis(y_true, y_proba, thresholds=[0.2, 0.5, 0.8])
    fig = plot_expanded_threshold_analysis(table, recommended_threshold=0.5, model_display_name="Test Model")
    assert fig is not None
